/** `ChannelInput.icon` holds at most 16 UTF-16 code units. */
export const MAX_ICON_LENGTH = 16;

const segmenter = new Intl.Segmenter(undefined, { granularity: "grapheme" });

/** The first grapheme of a suggestion, if it fits the icon column. */
export const clampEmoji = (value: string): string | undefined => {
  const [first] = segmenter.segment(value.trim());
  const grapheme = first?.segment;
  return grapheme && grapheme.length <= MAX_ICON_LENGTH ? grapheme : undefined;
};
